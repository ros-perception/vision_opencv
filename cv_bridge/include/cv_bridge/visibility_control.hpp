#ifndef CV_BRIDGE__VISIBILITY_CONTROL_HPP_
#define CV_BRIDGE__VISIBILITY_CONTROL_HPP_

// CV_BRIDGE_EXPORT and CV_BRIDGE_NO_EXPORT are generated by CMake (generate_export_header) and
// already resolve to dllexport or dllimport depending on whether the library is being built.
// The macros below are aliases of them, so that both sets can be used in the same translation
// unit without redefining each other.
#include "cv_bridge/cv_bridge_export.h"

#define CV_BRIDGE_PUBLIC CV_BRIDGE_EXPORT
#define CV_BRIDGE_PUBLIC_TYPE CV_BRIDGE_EXPORT
#define CV_BRIDGE_LOCAL CV_BRIDGE_NO_EXPORT

#endif  // CV_BRIDGE__VISIBILITY_CONTROL_HPP_
